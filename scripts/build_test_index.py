"""Generate a JavaScript test index for Zuxriddin Academy (no dependencies)."""
from __future__ import annotations
import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUBJECTS = {"reading", "listening", "speaking", "grammar", "vocabulary"}
LEVELS = {"a1", "a2", "b1", "b2", "c1", "c2"}

class TitleParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.inside_title = False
        self.title = []

    def handle_starttag(self, tag, attrs):
        if tag.lower() == "title":
            self.inside_title = True

    def handle_endtag(self, tag):
        if tag.lower() == "title":
            self.inside_title = False

    def handle_data(self, data):
        if self.inside_title:
            self.title.append(data)

def extract_title(path: Path) -> str:
    parser = TitleParser()
    parser.feed(path.read_text(encoding="utf-8-sig"))
    title = " ".join("".join(parser.title).split())
    title = re.split(r"\s*[|–—]\s*Zuxriddin Academy", title, flags=re.I)[0].strip()
    return title or path.stem.replace("-", " ").replace("_", " ").title()

def identify(path: Path):
    parts = [p.lower() for p in path.relative_to(ROOT).parts]
    if len(parts) >= 4 and parts[0] == "tests" and parts[1] in SUBJECTS and parts[2] in LEVELS:
        return parts[1], parts[2].upper()
    if len(parts) == 1 and parts[0] == "reading-museums.html":
        return "reading", "A2"  # Already created in the first lessons
    if len(parts) == 1:
        match = re.fullmatch(r"(reading|listening|speaking|grammar|vocabulary)-(a1|a2|b1|b2|c1|c2)-.+\.html", parts[0])
        if match:
            return match.group(1), match.group(2).upper()
    return None

def main():
    records = []
    for path in ROOT.rglob("*.html"):
        if any(piece.startswith(".") for piece in path.relative_to(ROOT).parts):
            continue
        section = identify(path)
        if not section:
            continue
        subject, level = section
        records.append({
            "subject": subject,
            "level": level,
            "title": extract_title(path),
            "url": path.relative_to(ROOT).as_posix(),
        })
    records.sort(key=lambda r: (r["subject"], r["level"], r["url"]), reverse=False)
    output = "// Auto-generated by scripts/build_test_index.py. Do not edit manually.\n"
    output += "window.ZUX_TESTS = " + json.dumps(records, ensure_ascii=False, indent=2) + ";\n"
    (ROOT / "testlar.js").write_text(output, encoding="utf-8")
    print(f"Indexed {len(records)} test(s): " + ", ".join(r["url"] for r in records))

if __name__ == "__main__":
    main()
